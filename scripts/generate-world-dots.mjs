/**
 * Generates src/lib/worldDots.ts — the dot lattice the hero map is drawn from.
 *
 * `svg-dotted-map` samples a world GeoJSON onto a regular grid and keeps the
 * cells that land on a country. Running that in the browser would ship the
 * GeoJSON and re-project it on every visit, so it runs here instead and the
 * result is committed as plain integers: the library stays a devDependency.
 *
 * Usage: npm run map:dots
 */
import { writeFileSync } from "node:fs";
import { createMap } from "svg-dotted-map";

/* 2:1 box, matching the hero panel once its parallax overscan is included. */
const WIDTH = 200;
const HEIGHT = 100;
const MAP_SAMPLES = 7000;
const RADIUS = 0.3; // library default; only affects the grid inset

/* Markers pulse over the lattice. Snapped to the same grid by the library, so
   they always sit exactly on a dot rather than floating between rows. */
const CITIES = [
  { name: "London", lat: 51.5074, lng: -0.1278, hub: true },
  { name: "New York", lat: 40.7128, lng: -74.006 },
  { name: "Dubai", lat: 25.2048, lng: 55.2708 },
  { name: "Singapore", lat: 1.3521, lng: 103.8198 },
  { name: "Sao Paulo", lat: -23.5505, lng: -46.6333 },
  { name: "Sydney", lat: -33.8688, lng: 151.2093 },
];

/* The library's own grid maths (dist/index.js): rows from the sample count and
   aspect, columns from the rows. Mirrored here to turn x/y back into col/row. */
const aspect = WIDTH / HEIGHT;
const rows = Math.round(Math.sqrt(MAP_SAMPLES / aspect));
const cols = Math.round(rows * aspect);
const inset = RADIUS * 1.25;
const spanX = WIDTH - 2 * inset;
const spanY = HEIGHT - 2 * inset;

const toCol = (x) => Math.round(((x - inset) / spanX) * (cols - 1));
const toRow = (y) => Math.round(((y - inset) / spanY) * (rows - 1));

const { points, addMarkers } = createMap({ width: WIDTH, height: HEIGHT, mapSamples: MAP_SAMPLES, radius: RADIUS });

const indices = points.map((p) => toRow(p.y) * cols + toCol(p.x)).sort((a, b) => a - b);

/* Coastal cities often snap to a cell the sampler rejected as sea, which would
   leave the marker hanging just off the coastline. Pull each one to the nearest
   land cell so every marker sits on a real dot. */
const land = new Set(indices);
function snap(col, row) {
  if (land.has(row * cols + col)) return { col, row };
  for (let ring = 1; ring <= 4; ring++) {
    let best = null;
    let bestDist = Infinity;
    for (let dr = -ring; dr <= ring; dr++) {
      for (let dc = -ring; dc <= ring; dc++) {
        const r = row + dr;
        const c = col + dc;
        if (r < 0 || r >= rows || c < 0 || c >= cols) continue;
        if (!land.has(r * cols + c)) continue;
        const dist = dr * dr + dc * dc;
        if (dist < bestDist) {
          bestDist = dist;
          best = { col: c, row: r };
        }
      }
    }
    if (best) return best;
  }
  throw new Error(`no land cell within 4 rings of ${col},${row}`);
}

const markers = addMarkers(CITIES).map((m) => ({
  name: m.name,
  hub: Boolean(m.hub),
  ...snap(toCol(m.x), toRow(m.y)),
}));

/* Guard against a silent grid-maths drift: every dot must be a unique, in-range cell. */
const cells = rows * cols;
const bad = indices.filter((i) => !Number.isInteger(i) || i < 0 || i >= cells);
if (bad.length) throw new Error(`${bad.length} dot(s) fell outside the ${cols}x${rows} grid`);
if (new Set(indices).size !== indices.length) throw new Error("duplicate grid cells — grid maths is out of sync with the library");

/* Deltas keep the committed file small: sorted indices rarely jump far. */
const deltas = indices.map((v, i) => (i === 0 ? v : v - indices[i - 1]));

const file = `// Generated by scripts/generate-world-dots.mjs — do not edit by hand.
// Run \`npm run map:dots\` to regenerate.

/** Lattice width in cells. */
export const COLS = ${cols};
/** Lattice height in cells. */
export const ROWS = ${rows};

/**
 * Land cells as gap-encoded \`row * COLS + col\` indices, ascending.
 * Decoded by {@link decodeDots}; stored as gaps purely to keep the file small.
 */
const PACKED: number[] = [${deltas.join(",")}];

/** Restores the absolute cell indices. */
export function decodeDots(): number[] {
  const out = new Array<number>(PACKED.length);
  let cursor = 0;
  for (let i = 0; i < PACKED.length; i++) {
    cursor += PACKED[i];
    out[i] = cursor;
  }
  return out;
}

export interface MapMarker {
  name: string;
  /** The primary marker: drawn larger, and the origin of the ripple. */
  hub: boolean;
  col: number;
  row: number;
}

export const MARKERS: MapMarker[] = ${JSON.stringify(markers, null, 2)};
`;

writeFileSync(new URL("../src/lib/worldDots.ts", import.meta.url), file);

console.log(`grid ${cols}x${rows} (${cells} cells) · ${indices.length} land dots · ${markers.length} markers`);
console.log(`packed ${(file.length / 1024).toFixed(1)}KB`);
